def build_universe() -> list[TickerEntry]:
    """Return full universe. Existing entries override SEC tier."""
    seen: dict[str, TickerEntry] = {}

    # Tier 4 first (lowest priority)
    for ticker, sector in _SEC_UNIVERSE:
        t = ticker.upper()
        if t not in seen:
            seen[t] = TickerEntry(t, sector, 4)

    # Existing entries override (higher priority)
    for entry in _EXISTING:
        seen[entry.ticker.upper()] = entry

    return sorted(seen.values(), key=lambda e: (e.tier, e.ticker))


UNIVERSE = build_universe()


def get_by_sector(sector: str) -> list[TickerEntry]:
    return [e for e in UNIVERSE if e.sector == sector]


def get_by_tier(tier: int) -> list[TickerEntry]:
    return [e for e in UNIVERSE if e.tier == tier]


def summary() -> None:
    from collections import Counter
    tier_counts   = Counter(e.tier   for e in UNIVERSE)
    sector_counts = Counter(e.sector for e in UNIVERSE)
    print(f"Total tickers: {len(UNIVERSE)}")
    print("\nBy tier:")
    for tier in sorted(tier_counts):
        label = {1: "S&P 500", 2: "Russell 1000", 3: "Edge cases", 4: "SEC universe"}.get(tier, f"Tier {tier}")
        print(f"  Tier {tier} ({label}): {tier_counts[tier]}")
    print("\nBy sector:")
    for sector, count in sector_counts.most_common():
        print(f"  {sector:<30} {count:>5}")


if __name__ == "__main__":
    summary()
